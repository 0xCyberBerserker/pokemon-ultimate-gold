/* Verify the real lazy catalog, filters, complete blocks and language selection. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WIKI_URL || 'http://127.0.0.1:8767/web/wiki/';
(async () => {
  const manifest = JSON.parse(await fs.readFile(path.join(__dirname, '../patches/manifest.json'), 'utf8'));
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}, permissions:['clipboard-read','clipboard-write']});
  const page = await context.newPage();
  const errors = [], catalogRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('cheat-catalog.json')) catalogRequests.push(request.url()); });
  await page.goto(base);
  await page.locator('#language').waitFor();
  assert.equal(catalogRequests.length, 0);
  await page.selectOption('#language','es');
  await page.goto(base + '#/guide/cheats');
  await page.locator('.guide a[href="#/cheats"]').click();
  await page.getByRole('heading',{name:'Catálogo de trucos',exact:true}).waitFor();
  assert.equal(catalogRequests.length, 1);
  assert.equal(await page.locator('.cheat-card').count(), 24);
  await page.locator('#cheat-next').click();
  assert.equal(await page.locator('#cheat-page').innerText(), '2 / 88');
  await page.locator('#cheat-query').fill('capturar entrenadores');
  assert.equal(await page.locator('.cheat-card').count(), 1);
  await page.locator('.cheat-card > details > summary').click();
  const code = await page.locator('.cheat-card pre code').innerText();
  assert.equal(code, '9224670A 00002101\n1224670A 00002100\nD2000000 00000000');
  assert.match(await page.locator('.cheat-card').innerText(), /guardar y reiniciar/);
  await page.locator('.cheat-copy').click();
  await page.getByRole('button',{name:'Copiado',exact:true}).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), code);
  const downloaded = page.waitForEvent('download');
  await page.locator('.cheat-download').click();
  const download = await downloaded;
  const profile = await fs.readFile(await download.path(),'utf8');
  assert.match(profile, /cheat0_enable = "false"/);
  assert(profile.includes(`cheat0_code = "${code.split('\n').join('+')}"`));
  assert(profile.includes(`target_sha256: ${manifest.target.sha256}`));
  await page.locator('#cheat-query').fill('');
  await page.locator('#cheat-status').selectOption('guard_mismatch');
  assert.equal(await page.locator('.cheat-card').count(), 6);
  assert.match(await page.locator('.cheat-card').first().innerText(), /no coincide con esta ROM/);
  await page.selectOption('#language','en');
  await page.getByRole('heading',{name:'Cheat catalog',exact:true}).waitFor();
  assert.equal(catalogRequests.length, 1);
  await page.locator('#cheat-query').fill('trainer-owned');
  assert.equal(await page.locator('.cheat-card').count(), 1);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log(JSON.stringify({result:'PASS',checks:['lazy 2110-entry catalog','pagination','Spanish search','complete trainer-capture code','clipboard','disabled exact-target profile download','six mismatched guards visible','language selector','mobile width']}));
})().catch(error => { console.error(error); process.exit(1); });
