/* Verify game-mode comparisons and target-native ability slot labels. */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WIKI_URL || 'http://127.0.0.1:8767/web/wiki/';
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto(base+'#/pokemon/35');
  await page.selectOption('#language','es');
  await page.locator('.ability-slots').waitFor();
  assert.equal(await page.locator('.ability-slots .ability').count(),3);
  assert.match(await page.locator('.ability-slots').innerText(),/Habilidad estándar 1/);
  assert.match(await page.locator('.ability-slots').innerText(),/Habilidad estándar 2/);
  assert.match(await page.locator('.ability-hidden').innerText(),/no implementa una tercera ranura/);
  await page.goto(base+'#/trainers');
  await page.locator('#trainer-filter').fill('Silver');
  await page.locator('#trainer-pokemon').fill('Kadabra');
  const card=page.locator('.trainer-card[data-trainer-id="1"]');
  await card.locator('summary').click();
  await card.locator('.team-member').first().waitFor();
  assert.match(await card.locator('.team').innerText(),/Kadabra · Nv 19/);
  const before=await card.locator('progress').evaluateAll(nodes=>nodes.map(node=>node.value));
  await page.selectOption('#game-mode','plus');
  await card.locator('.team-member').first().waitFor();
  assert.match(await card.locator('.team').innerText(),/Kadabra · Nv 21/);
  assert.equal(await page.locator('#trainer-filter').inputValue(),'Silver');
  assert.equal(await page.locator('#trainer-pokemon').inputValue(),'Kadabra');
  assert.equal(await card.locator('details').getAttribute('open'),'');
  assert.deepEqual(await card.locator('progress').evaluateAll(nodes=>nodes.map(node=>node.value)),before);
  assert.match(await page.locator('.mode-note').innerText(),/IV y EV se conservan/);
  await page.reload();
  await page.locator('#trainer-kind').waitFor();
  assert.equal(await page.locator('#game-mode').inputValue(),'plus');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.selectOption('#language','en');
  assert.equal(await page.locator('#game-mode').getAttribute('aria-label'),'Game mode');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log(JSON.stringify({result:'PASS',checks:['standard slots 1/2','hidden slot absence explicit','Normal/Plus exact levels','unchanged IV/EV charts','expanded team and filters retained','mode persistence','mobile topbar','selected-language labels']}));
})().catch(error=>{console.error(error);process.exit(1)});
