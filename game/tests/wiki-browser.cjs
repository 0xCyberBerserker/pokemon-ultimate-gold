/* Run with PLAYWRIGHT_MODULE pointing to an existing audited installation. */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WIKI_URL || 'http://127.0.0.1:8767/web/wiki/';
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1280, height: 900}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(base + 'evolution-items-qol.html');
  await page.waitForURL('**/#/guide/items');
  await page.waitForSelector('#language');
  await page.selectOption('#language', 'es');
  await page.goto(base + '#/pokemon/35');
  await page.getByRole('heading', {name: '#35 Clefairy', exact: true}).waitFor();
  assert.match(await page.locator('#content').innerText(), /Hada/);
  assert.match(await page.locator('#content').innerText(), /Usa Moon Stone/);
  assert.equal(await page.locator('#content progress').count(), 6);
  assert(await page.locator('.sprite').first().evaluate(image => image.complete && image.naturalWidth > 0));
  await page.locator('#search').fill('test');
  await page.locator('#search').fill('');
  await page.goto(base + '#/moves/27');
  await page.getByRole('heading', {name: 'Voz Cautivadora', exact: true}).waitFor();
  await page.goto(base + '#/items/467');
  await page.locator('#content h1').filter({hasText:'Covenant Orb'}).waitFor();
  assert.match(await page.locator('#content h1').innerText(), /Orbe Pacto/);
  await page.goto(base + '#/items/82');
  await page.locator('#content h1').filter({hasText:'Fire Stone'}).waitFor();
  assert.match(await page.locator('#content h1').innerText(), /Piedra Fuego/);
  assert.match(await page.locator('.acquisition').innerText(), /Centro Comercial de Ciudad Trigal 2F/);
  assert.match(await page.locator('.acquisition').innerText(), /2,100/);
  assert.match(await page.locator('.acquisition').innerText(), /compra en juego no se ha probado/i);
  await page.goto(base + '#/items/107');
  await page.locator('#content h1').filter({hasText:'Shiny Stone'}).waitFor();
  assert.match(await page.locator('#content h1').innerText(), /Piedra Día/);
  assert.match(await page.locator('.acquisition').innerText(), /Tienda de Ciudad Endrino/);
  assert.match(await page.locator('.acquisition').innerText(), /entrada del Frente Batalla/);
  for (const [id, english, spanish] of [[114,'Party Healer','Curador del equipo'],[118,'Cheat Kit','Kit de trucos']]) {
    await page.goto(base + '#/items/' + id);
    await page.locator('#content h1').filter({hasText:english}).waitFor();
    assert.match(await page.locator('#content h1').innerText(), new RegExp(spanish));
    assert.match(await page.locator('.acquisition-status').innerText(), /Regalo observado.*guardado posterior sin probar/);
    await page.locator('.acquisition-evidence > summary').click();
    assert.match(await page.locator('.acquisition-evidence').innerText(), /Regalo observado/);
    assert.doesNotMatch(await page.locator('.acquisition-evidence').innerText(), /native_gift_runtime_only/);
    const icon=page.locator('#content article > img');
    await icon.evaluate(image=>image.decode());
    assert(await icon.evaluate(image=>image.naturalWidth>0));
    const capture=page.locator('.acquisition-capture img');
    await capture.scrollIntoViewIfNeeded();
    await capture.evaluate(image=>image.decode());
    assert.equal(await capture.evaluate(image=>image.naturalHeight),384);
  }
  await page.goto(base + '#/pokemon');
  await page.locator('#dex-gen').selectOption('1');
  await page.locator('#dex-type').selectOption('9');
  await page.locator('#dex-name').fill('clefairy');
  assert.equal(await page.locator('.dex-card:visible').count(), 1);
  await page.locator('#dex-gen').selectOption('2');
  assert.equal(await page.locator('.dex-card:visible').count(), 0);
  await page.goto(base + '#/trainers');
  assert.match(await page.locator('.journey-stage:visible h2').first().innerText(), /Ciudad Cerezo/);
  await page.locator('#trainer-filter').fill('Silver');
  await page.locator('#trainer-pokemon').fill('Murkrow');
  const visibleTeams = await page.locator('.trainer-card:visible').allTextContents();
  assert(visibleTeams.length > 0 && visibleTeams.length < 737);
  assert(visibleTeams.every(team => team.includes('Silver') && team.includes('Murkrow')));
  assert(await page.locator('.trainer-portrait:visible').first().evaluate(image => image.complete && image.naturalWidth === 160));
  await page.locator('.trainer-card:visible .trainer-roster > summary').first().click();
  await page.locator('.trainer-card:visible .iv-ev-panel').first().waitFor();
  assert.equal(await page.locator('.trainer-card:visible .iv-grid').first().locator('progress').count(), 6);
  assert.equal(await page.locator('.trainer-card:visible .ev-grid').first().locator('progress').count(), 6);
  assert(await page.locator('.trainer-card:visible .trainer-moves').first().locator('.move-chip').count() > 0);
  await page.locator('#trainer-filter').fill('');
  await page.locator('#trainer-pokemon').fill('');
  await page.locator('#trainer-kind').selectOption('rematch');
  assert(await page.locator('.trainer-card:visible').count() > 0);
  assert(await page.locator('.trainer-card:visible').evaluateAll(cards => cards.every(card => card.dataset.kind === 'rematch')));
  await page.goto(base + '#/machines');
  assert.equal(await page.locator('.machine-row:visible').count(), 100);
  const firstMachine = page.locator('.machine-row').first();
  assert.equal(await firstMachine.locator('details').getAttribute('open'), null);
  await firstMachine.locator('summary').focus();
  await page.keyboard.press('Enter');
  assert.notEqual(await firstMachine.locator('details').getAttribute('open'), null);
  await firstMachine.locator('.acquisition').waitFor();
  const cardColors = await firstMachine.evaluate(card => ({surface:getComputedStyle(card).backgroundColor,badge:getComputedStyle(card.querySelector('.type')).backgroundColor}));
  assert.notEqual(cardColors.surface, cardColors.badge);
  const typeImages = page.locator('.machine-row .type img');
  assert.equal(await typeImages.count(), 100);
  assert(await typeImages.evaluateAll(images => images.every(image => image.complete && image.naturalWidth === 60)));
  await page.locator('#machine-type').selectOption('0');
  assert.equal(await page.locator('.machine-row:visible').count(), 25);
  await page.locator('#machine-type').selectOption('');
  await page.locator('#machine-kind').selectOption('hm');
  assert.equal(await page.locator('.machine-row:visible').count(), 8);
  assert.match(await page.locator('.machine-row:visible').first().innerText(), /^MO /);
  await page.selectOption('#language', 'en');
  assert.equal(await page.locator('#machine-kind option[value="tm"]').innerText(), 'TM');
  assert.equal(await page.locator('#machine-kind option[value="hm"]').innerText(), 'HM');
  await page.selectOption('#language', 'es');
  assert.equal(await page.locator('#machine-kind option[value="tm"]').innerText(), 'MT');
  assert.equal(await page.locator('#machine-kind option[value="hm"]').innerText(), 'MO');
  await page.goto(base + '#/guide/player');
  await page.locator('.guide').waitFor();
  assert.match(await page.locator('.guide').innerText(), /ROM/);
  assert.match(await page.locator('.guide').innerText(), /Esta versión conserva las 493 especies/);
  assert.doesNotMatch(await page.locator('.guide').innerText(), /This build keeps/);
  assert.doesNotMatch(await page.locator('.guide').innerText(), /^English$/m);
  await page.selectOption('#language', 'en');
  await page.reload();
  assert.equal(await page.locator('#language').inputValue(), 'en');
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  await page.setViewportSize({width: 390, height: 844});
  await page.goto(base + '#/pokemon/35');
  await page.getByRole('heading', {name: '#35 Clefairy', exact: true}).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({result: 'PASS', checks: ['legacy redirect', 'sprites and portraits', 'custom names', 'verified shop floor and price', 'shop runtime limit visible', 'combined filters', '100 type icons', 'Normal type filter', '8 HMs', 'language persistence', 'mobile width', 'no browser errors']}));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
