import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';

test('reference views render actual bilingual data and hash links', async () => {
  const data = JSON.parse(await readFile(new URL('../../web/data/wiki-data.json', import.meta.url)));
  const server = await createServer({ server: { middlewareMode: true, ws: false }, appType: 'custom' });
  try {
    const { default: Pokedex } = await server.ssrLoadModule('/src/features/pokedex/Pokedex.tsx');
    const { default: Reference } = await server.ssrLoadModule('/src/features/reference/Reference.tsx');
    const dex = renderToStaticMarkup(React.createElement(Pokedex, { data, language: 'es', id: 1 }));
    assert.match(dex, /Bulbasaur/);
    assert.match(dex, /Estadísticas base/);
    assert.match(dex, /#\/pokemon\/2/);
    assert.match(dex, /Nivel 16/);
    assert.match(dex, /class="pokemon-evolution"/);
    assert.match(dex, /sprites\/types\/12\.png/);
    assert.match(dex, /sprites\/pokemon\/2\.png/);
    assert.match(dex, /#\/abilities\/65/);
    const compatibleData = { ...data, tmhm_compatibility: { target_sha256: data.target_sha256, by_species: { '1': [data.tmhm[0].item_id] } } };
    const compatibleDex = renderToStaticMarkup(React.createElement(Pokedex, { data: compatibleData, language: 'es', id: 1 }));
    assert.match(compatibleDex, /MT y MO compatibles/);
    assert.match(compatibleDex, /MT 1/);
    assert.match(compatibleDex, new RegExp(`href="#/items/${data.tmhm[0].item_id}"`));
    const mismatchedData = { ...compatibleData, tmhm_compatibility: { ...compatibleData.tmhm_compatibility, target_sha256: 'not-the-target' } };
    const mismatchedDex = renderToStaticMarkup(React.createElement(Pokedex, { data: mismatchedData, language: 'es', id: 1 }));
    assert.match(mismatchedDex, /compatibilidad individual aún no está disponible/);
    const list = renderToStaticMarkup(React.createElement(Pokedex, { data, language: 'en' }));
    assert.equal((list.match(/class="dex-card"/g) || []).length, 60);
    assert.ok(list.includes(` / ${data.species.length}`));
    assert.match(list, /sprites\/types\/12\.png/);
    const move = renderToStaticMarkup(React.createElement(Reference, { data, language: 'es', route: '#/moves/27' }));
    const ability = renderToStaticMarkup(React.createElement(Reference, { data, language: 'es', route: '#/abilities/65' }));
    assert.match(ability, /Espesura/);
    assert.match(ability, /#\/pokemon\/1/);
    const abilities = renderToStaticMarkup(React.createElement(Reference, { data, language: 'es', route: '#/abilities' }));
    assert.equal((abilities.match(/class="panel ability-card"/g) || []).length, Object.keys(data.abilities).length);
    assert.match(abilities, /class="reference-list ability-list reference-list--rows"/);
    assert.match(abilities, /href="#\/abilities\/65"/);
    assert.match(move, /Voz Cautivadora/);
    assert.match(move, /Hada/);
    assert.match(move, /<dt>Potencia<\/dt><dd>40<\/dd>/);
    assert.match(move, /sprites\/types\/9\.png/);
    const items = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/items' }));
    assert.match(items, /class="reference-list reference-list--rows"/);
    assert.match(items, /<details class="panel item-entry"/);
    assert.match(items, /sprites\/items\/1\.png/);
    assert.match(items, /href="#\/items\/1"/);
    assert.match(items, /ROM placeholder icon/);
    assert.match(items, /Goldenrod Department Store 2F/);
    const guide = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/guide/player' }));
    assert.ok(guide.includes(data.guides.player.title.en));
    for (const language of ['en', 'es']) {
      const index = renderToStaticMarkup(React.createElement(Reference, { data, language, route: '#/guides' }));
      assert.ok(index.includes(language === 'es' ? 'Documentación técnica' : 'Technical documentation'));
      for (const id of Object.keys(data.guides)) assert.equal((index.match(new RegExp(`href="#/guide/${id}"`, 'g')) || []).length, 1, id);
    }
    const missingGuide = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/guide/not-a-real-guide' }));
    assert.match(missingGuide, /Entry unavailable/);
    const evolution = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/evolutions' }));
    const eeveeFamily = evolution.match(/<article class="evolution-family[^\"]*"[^>]*>[\s\S]*?<\/article>/g)?.find((html) => html.includes('Eevee family'));
    assert.ok(eeveeFamily);
    for (const species of ['Vaporeon', 'Jolteon', 'Flareon', 'Espeon', 'Umbreon', 'Leafeon', 'Glaceon']) assert.ok(eeveeFamily.includes(species));
    assert.equal((eeveeFamily.match(/class="evolution-edge"/g) || []).length, 7);
    const item = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/items/2' }));
    assert.ok(item.includes('Goldenrod Department Store 2F'));
    assert.ok(item.includes('A live purchase has not been tested.'));
    assert.ok(item.includes('shop-locations-alpha2.json'));
    assert.ok(item.includes(data.target_sha256));
    const machines = renderToStaticMarkup(React.createElement(Reference, { data, language: 'es', route: '#/machines' }));
    assert.match(machines, /class="reference-list reference-list--rows"/);
    assert.match(machines, /MT 1 · Puño Certero/);
    assert.match(machines, /También se puede comprar en Ciudad Azafrán/);
    const moves = renderToStaticMarkup(React.createElement(Reference, { data, language: 'en', route: '#/moves' }));
    assert.match(moves, /class="reference-list reference-list--rows"/);
    const { default: Acquisition } = await server.ssrLoadModule('/src/features/reference/Acquisition.tsx');
    const bounded = renderToStaticMarkup(React.createElement(Acquisition, { language: 'en', records: data.items['81'].acquisition }));
    assert.match(bounded, /Scope: Purchase and save\/reload verified in a bounded case/);
    assert.match(bounded, /qa-alpha2-shop/);
    const compared = renderToStaticMarkup(React.createElement(Acquisition, { language: 'en', records: data.items['87'].acquisition }));
    assert.match(compared, /Base ROM SHA-256/);
    assert.match(compared, /65f02a56842b75aa92d775d56d657a56/);
    assert.match(compared, /href="#\/pokemon\/46"/);
    const upstream = renderToStaticMarkup(React.createElement(Acquisition, { language: 'en', records: data.items['80'].acquisition }));
    assert.match(upstream, /Upstream documentation; not verified in this target ROM/);
    assert.match(upstream, /pokemon-sacred-gold-storm-silver-important-item-locations/);
    const claims = new Set(Object.values(data.items).flatMap((item) => (item.acquisition || []).map((record) => record.source?.claim).filter(Boolean)));
    for (const claim of claims) {
      const spanish = renderToStaticMarkup(React.createElement(Acquisition, { language: 'es', records: [{ source: { claim } }] }));
      assert.ok(!spanish.includes(claim), `Missing Spanish source claim: ${claim}`);
    }
    const unsafe = renderToStaticMarkup(React.createElement(Acquisition, { language: 'en', records: [{ method: { en: 'example', es: 'ejemplo' }, evidence: { report: { path: 'https://outside.invalid/report' }, screenshots: [{ path: '//outside.invalid/photo.png' }] } }] }));
    assert.doesNotMatch(unsafe, /outside\.invalid/);
    const galleryData = JSON.parse(await readFile(new URL('../../web/data/kris-gallery.json', import.meta.url)));
    const { default: KrisGallery } = await server.ssrLoadModule('/src/features/kris/KrisGallery.tsx');
    const gallery = renderToStaticMarkup(React.createElement(KrisGallery, { language: 'es', initialManifest: galleryData }));
    assert.match(gallery, /Una primera variante experimental/);
    assert.match(gallery, /no identifica qué captura corresponde/);
    assert.match(gallery, /El orden no demuestra la cronología entre pruebas distintas/);
    const archiveStart = gallery.indexOf('<details><summary>Archivo técnico completo y filtros</summary>');
    assert.ok(archiveStart > 0);
    assert.equal((gallery.slice(0, archiveStart).match(/class="kris-gallery-card"/g) || []).length, 3);
    assert.equal((gallery.slice(archiveStart).match(/class="kris-gallery-card"/g) || []).length, 24);
    assert.ok(gallery.slice(archiveStart).includes(`${galleryData.images.length} capturas`));
    const cheatData = JSON.parse(await readFile(new URL('../../web/data/cheat-catalog.json', import.meta.url)));
    const { default: CheatCatalog } = await server.ssrLoadModule('/src/features/cheats/CheatCatalog.tsx');
    const cheats = renderToStaticMarkup(React.createElement(CheatCatalog, { language: 'es', target: cheatData.target_sha256, initialCatalog: cheatData }));
    assert.match(cheats, /Catálogo de trucos/);
    assert.match(cheats, /Condición incompatible con la ROM/);
    assert.match(cheats, /92002346 00000E41/);
    assert.equal((cheats.match(/class="cheat-card"/g) || []).length, 24);
    const boundedCheats = { ...cheatData, entries: cheatData.entries.filter((entry) => ['00-006', '80-002'].includes(entry.id)) };
    const boundedCheatHtml = renderToStaticMarkup(React.createElement(CheatCatalog, { language: 'es', target: cheatData.target_sha256, initialCatalog: boundedCheats }));
    const boundedCards = boundedCheatHtml.match(/<article class="cheat-card"[\s\S]*?<\/article>/g) || [];
    assert.equal(boundedCards.length, 2);
    for (const card of boundedCards) {
      assert.match(card, /Sintaxis comprobada · efecto sin probar/);
      assert.match(card, /Prueba RAM acotada en Alfa 1/);
    }
    const mismatch = renderToStaticMarkup(React.createElement(CheatCatalog, { language: 'es', target: 'different', initialCatalog: cheatData }));
    assert.doesNotMatch(mismatch, /92002346 00000E41/);
    globalThis.localStorage = { getItem: () => null };
    globalThis.location = { hash: '#/evolutions' };
    globalThis.matchMedia = () => ({ matches: false });
    const { default: App } = await server.ssrLoadModule('/src/App.tsx');
    const shell = renderToStaticMarkup(React.createElement(App));
    assert.match(shell, /href="#\/evolutions"/);
    assert.match(shell, /href="#\/mechanics"/);
    assert.match(shell, /href="#\/faq"/);
    assert.match(shell, /href="\.\.\/LICENSES\.html"/);
    assert.match(shell, /href="#\/guide\/progress"/);
    assert.match(shell, /href="#\/guide\/sources-inventory"/);
    assert.match(shell, /Getting started/);
    assert.equal((shell.match(/aria-current="page"/g) || []).length, 1);
    for (const route of ['#/guide/progress', '#/guide/sources-inventory']) {
      globalThis.location.hash = route;
      const selected = renderToStaticMarkup(React.createElement(App));
      assert.equal((selected.match(/aria-current="page"/g) || []).length, 1, route);
    }
    globalThis.localStorage = { getItem: () => { throw new Error('SecurityError'); } };
    assert.match(renderToStaticMarkup(React.createElement(App)), /app-shell/);
    delete globalThis.localStorage; delete globalThis.location; delete globalThis.matchMedia;
  } finally { await server.close(); }
});
